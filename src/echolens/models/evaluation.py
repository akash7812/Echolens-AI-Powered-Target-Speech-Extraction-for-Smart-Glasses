
import numpy as np


def si_sdr(reference, estimate):
    """
    Calculate Scale-Invariant Signal-to-Distortion Ratio (SI-SDR).

    Higher values indicate better similarity to the clean reference.
    """

    reference = np.asarray(reference, dtype=np.float64)
    estimate = np.asarray(estimate, dtype=np.float64)

    if reference.ndim != 1 or estimate.ndim != 1:
        raise ValueError("Audio signals must be mono.")

    if len(reference) == 0 or len(estimate) == 0:
        raise ValueError("Audio signals cannot be empty.")

    if len(reference) != len(estimate):
        raise ValueError("Audio signals must have equal lengths.")

    if not np.isfinite(reference).all():
        raise ValueError("Reference contains invalid values.")

    if not np.isfinite(estimate).all():
        raise ValueError("Estimate contains invalid values.")

    reference = reference - np.mean(reference)
    estimate = estimate - np.mean(estimate)

    reference_energy = np.sum(reference ** 2)

    if reference_energy < 1e-10:
        raise ValueError("Reference signal has insufficient energy.")

    scale = np.dot(estimate, reference) / reference_energy

    projected = scale * reference
    noise = estimate - projected

    target_energy = np.sum(projected ** 2)
    noise_energy = np.sum(noise ** 2)

    return float(
        10 * np.log10(
            (target_energy + 1e-10) /
            (noise_energy + 1e-10)
        )
    )


def evaluate_sample(sample, extracted):
    """
    Evaluate one PS4 extraction result.

    Required sample fields:
        mixture
        target
        sample_rate

    extracted:
        Audio generated by PS4.
    """

    mixture = sample["mixture"]
    target = sample["target"]

    mixture_score = si_sdr(target, mixture)
    extracted_score = si_sdr(target, extracted)

    improvement = extracted_score - mixture_score

    return {
        "sample_rate": sample["sample_rate"],
        "mixture_si_sdr": mixture_score,
        "extracted_si_sdr": extracted_score,
        "si_sdr_improvement": improvement
    }
